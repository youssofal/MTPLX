def test_recovery_fails_runs_with_missing_or_hash_invalid_pinned_graphs(tmp_path):
    _, workspace_store, workspace, graph_store, tools, memory = _stores(tmp_path)

    def create_graph(identifier):
        return graph_store.create(
            {
                "id": identifier,
                "workspace_id": workspace.id,
                "project_id": workspace.id,
                "name": identifier,
                "nodes": [
                    {"id": "input", "type": "input"},
                    {"id": "output", "type": "output"},
                ],
                "edges": [{"source": "input", "target": "output"}],
            }
        )

    missing_graph = create_graph("missing-pinned-graph")
    missing_run = graph_store.create_run(missing_graph)
    graph_store._revision_path(missing_graph.id, missing_graph.revision).unlink()

    invalid_graph = create_graph("invalid-pinned-graph")
    invalid_run = graph_store.create_run(invalid_graph)
    invalid_path = graph_store._revision_path(invalid_graph.id, invalid_graph.revision)
    invalid_payload = json.loads(invalid_path.read_text(encoding="utf-8"))
    invalid_payload["name"] = "tampered"
    invalid_path.write_text(json.dumps(invalid_payload), encoding="utf-8")

    executor = GraphExecutor(graph_store, tools, memory)
    try:
        for run_id in (missing_run.id, invalid_run.id):
            run = graph_store.get_run(run_id)
            assert run.status == "failed"
            assert "cannot recover pinned Graph revision" in run.error
            assert workspace_store.get_run(run_id).status == "failed"
            events = workspace_store.list_events(run_id, limit=100)
            assert any(event.kind == "graph_recovery_failed" for event in events)
    finally:
        executor.close()


def test_approval_denial_and_cancellation_clear_durable_approval_state(tmp_path):
    _, workspace_store, workspace, graph_store, tools, memory = _stores(tmp_path)
    graph = graph_store.create(
        {
            "id": "approval-terminal-states",
            "workspace_id": workspace.id,
            "project_id": workspace.id,
            "name": "Approval terminal states",
            "nodes": [
                {"id": "input", "type": "input"},
                {
                    "id": "approval",
                    "type": "human_approval",
                    "config": {"action": "Continue"},
                },
                {"id": "output", "type": "output"},
            ],
            "edges": [
                {"source": "input", "target": "approval"},
                {"source": "approval", "target": "output"},
            ],
        }
    )
    executor = GraphExecutor(graph_store, tools, memory)
    try:
        denied = executor.start(graph.id)
        denied = _wait_for(
            graph_store,
            denied.id,
            lambda value: value.status == "waiting_approval",
        )
        denied_approval = workspace_store.get_approval(denied.pending_approval_id)
        denied = executor.approve(
            denied.id,
            denied_approval.id,
            "denied",
            resolved_by="test",
        )
        assert denied.status == "failed"
        assert denied.pending_approval_id is None
        assert denied.node_states["approval"]["status"] == "failed"
        assert denied.node_states["approval"]["pending_approval_id"] is None
        assert workspace_store.get_approval(denied_approval.id).status == "denied"

        cancelled = executor.start(graph.id)
        cancelled = _wait_for(
            graph_store,
            cancelled.id,
            lambda value: value.status == "waiting_approval",
        )
        cancelled_approval = workspace_store.get_approval(
            cancelled.pending_approval_id
        )
        cancelled = executor.cancel(cancelled.id)
        assert cancelled.status == "cancelled"
        assert cancelled.pending_approval_id is None
        assert cancelled.node_states["approval"]["status"] == "cancelled"
        assert workspace_store.get_approval(cancelled_approval.id).status == "denied"
        with pytest.raises(GraphExecutionError, match="cannot resolve approval"):
            executor.approve(
                cancelled.id,
                cancelled_approval.id,
                "approved",
            )
        with pytest.raises(WorkspaceConflictError, match="terminal graph run is immutable"):
            graph_store.update_run(cancelled.id, error="contradictory terminal state")
    finally:
        executor.close()


def test_restart_commits_prepared_completion_without_duplicate_events(tmp_path):
    _, workspace_store, workspace, graph_store, tools, memory = _stores(tmp_path)
    graph = graph_store.create(
        {
            "id": "prepared-completion-recovery",
            "workspace_id": workspace.id,
            "project_id": workspace.id,
            "name": "Prepared completion recovery",
            "outputs": {"result": {"type": "string"}},
            "nodes": [
                {"id": "input", "type": "input"},
                {
                    "id": "output",
                    "type": "output",
                    "config": {"mapping": {"result": "done"}},
                },
            ],
            "edges": [{"source": "input", "target": "output"}],
        }
    )
    run = graph_store.create_run(graph)
    states = {key: dict(value) for key, value in run.node_states.items()}
    states["input"].update(
        {"status": "completed", "output": {}, "completed_at": "checkpoint"}
    )
    states["output"].update(
        {
            "status": "completed",
            "attempts": 1,
            "output": {"result": "done"},
            "completed_at": "checkpoint",
        }
    )
    prepared = graph_store.update_run(
        run.id,
        status="running",
        outputs={"result": "done"},
        node_states=states,
        current_node_id="output",
        resource_metrics={
            "steps_completed": 2,
            "completion_prepared": True,
            "completion_prepared_at": "checkpoint",
        },
    )
    workspace_store.append_event(
        prepared.id,
        "graph_node_completed",
        {"node_id": "output", "node_type": "output", "attempt": 1},
    )
    workspace_store.append_event(
        prepared.id,
        "graph_completed",
        {
            "graph_id": graph.id,
            "graph_revision": graph.revision,
            "outputs": {"result": "done"},
        },
    )

    executor = GraphExecutor(graph_store, tools, memory)
    try:
        recovered = graph_store.get_run(prepared.id)
        assert recovered.status == "completed"
        assert recovered.outputs == {"result": "done"}
        assert recovered.resource_metrics["completion_committed_at"]
        assert "completion_prepared" not in recovered.resource_metrics
        kinds = [
            event.kind
            for event in workspace_store.list_events(prepared.id, limit=500)
        ]
        assert kinds.count("graph_node_completed") == 1
        assert kinds.count("graph_completed") == 1
        assert kinds.count("run_completed") == 1
    finally:
        executor.close()
