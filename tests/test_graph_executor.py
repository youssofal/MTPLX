def _wait_for(graph_store, run_id, predicate, *, timeout=10):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        run = graph_store.get_run(run_id)
        if predicate(run):
            return run
        time.sleep(0.01)
    run = graph_store.get_run(run_id)
    raise AssertionError(
        f"Graph run did not reach expected state: {run.status}, "
        f"node={run.current_node_id}, error={run.error}"
    )


def _stores(tmp_path, *, policy=None):
    project = tmp_path / "project"
    project.mkdir()
    workspace_store = WorkspaceStore(tmp_path / "state")
