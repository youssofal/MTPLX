def test_graph_runs_model_loop_tools_and_exact_approvals_to_recorded_completion(tmp_path):
    project, workspace_store, workspace, graph_store, tools, memory = _stores(tmp_path)
    calls = []

    def model_runner(**kwargs):
        calls.append(dict(kwargs))
        node_id = kwargs["node_id"]
        prompt = kwargs["messages"][0]["content"]
        content = "I am done" if node_id == "plan" else f"{node_id}: {prompt}"
        return {
            "model": kwargs["model"],
            "choices": [{"message": {"content": content}}],
            "usage": {"prompt_tokens": 4, "completion_tokens": 3},
            "mtplx_stats": {
                "session_cache_hit": node_id.endswith("body"),
                "ssd_cache_hit": node_id == "plan",
                "lock_wait_time_s": 0.002,
                "decode_tok_s": 42.5,
                "accepted_by_depth": [3, 2],
                "drafted_by_depth": [4, 4],
                "mtp_depth": 2,
            },
        }

    graph = graph_store.create(_full_graph(workspace.id))
    executor = GraphExecutor(
        graph_store,
        tools,
        memory,
        model_runner=model_runner,
    )
    try:
        run = executor.start(graph.id, inputs={"goal": "build it"})
        approval_tools = []
        while True:
            run = _wait_for(
                graph_store,
                run.id,
                lambda value: value.status in {
                    "waiting_approval",
                    "completed",
                    "failed",
                    "cancelled",
                },
            )
            if run.status != "waiting_approval":
                break
            approval = workspace_store.get_approval(run.pending_approval_id)
            approval_tools.append(approval.tool)
            executor.approve(run.id, approval.id, "approved", resolved_by="test")

        assert run.status == "completed", run.error
        assert run.outputs["plan"] == "I am done"
        assert len(run.outputs["iterations"]) == 2
        assert run.outputs["approved"] is True
        assert (project / "generated.txt").read_text(encoding="utf-8") == (
            "generated by Graph\n"
        )
        assert approval_tools == ["write_file", "run_tests", "graph_human_approval"]
        assert len(calls) == 3
        assert calls[0]["model"] == "mtplx-test-model"
        assert calls[1]["session_id"] == calls[2]["session_id"]
        plan_metrics = run.node_states["plan"]["metrics"]
        assert plan_metrics["model_load_wait_ms"] == 2
        assert plan_metrics["ssd_cache_hit"] is True
        assert plan_metrics["decode_tok_s"] == 42.5
        assert plan_metrics["acceptance_rate"] == pytest.approx(5 / 8)

        events = workspace_store.list_events(run.id, limit=1000)
        kinds = [event.kind for event in events]
        assert kinds.count("loop_iteration_completed") == 2
        assert kinds.count("tool_call") == 2
        assert kinds.count("test_started") == 1
        assert kinds.count("test_completed") == 1
        assert kinds.count("graph_completed") == 1
        assert kinds.count("run_completed") == 1
        assert all(
            approval.status == "consumed"
            for approval in workspace_store.list_approvals(run_id=run.id, limit=20)
        )
    finally:
        executor.close()


def test_loop_pause_checkpoints_and_resume_does_not_repeat_completed_iteration(tmp_path):
    _, _, workspace, graph_store, tools, memory = _stores(
        tmp_path,
        policy={"write": "allow", "terminal": "allow"},
    )
    entered = threading.Event()
    release = threading.Event()
    calls = []

    def model_runner(**kwargs):
        calls.append(kwargs["messages"][0]["content"])
        if len(calls) == 1:
            entered.set()
            assert release.wait(timeout=5)
        return {
            "model": kwargs["model"],
            "choices": [{"message": {"content": f"iteration-{len(calls)}"}}],
        }

    graph = graph_store.create(
        {
            "id": "pause-loop",
            "project_id": workspace.id,
            "workspace_id": workspace.id,
            "name": "Pause Loop",
            "limits": {"max_context_tokens": 8192, "max_steps": 10},
            "nodes": [
                {"id": "input", "type": "input"},
                {
                    "id": "loop",
                    "type": "loop",
                    "config": {
                        "max_iterations": 3,
                        "body": {
                            "type": "model",
                            "config": {"prompt": "Loop {{loop.index}}"},
                        },
                    },
                },
                {"id": "output", "type": "output"},
            ],
            "edges": [
                {"source": "input", "target": "loop"},
                {"source": "loop", "target": "output"},
            ],
        }
    )
    executor = GraphExecutor(graph_store, tools, memory, model_runner=model_runner)
    try:
        run = executor.start(graph.id)
        assert entered.wait(timeout=5)
        executor.pause(run.id)
        release.set()
        paused = _wait_for(graph_store, run.id, lambda value: value.status == "paused")
        assert paused.node_states["loop"]["status"] == "pending"
        assert paused.node_states["loop"]["iterations_completed"] == 1

        executor.resume(run.id)
        completed = _wait_for(
            graph_store,
            run.id,
            lambda value: value.status in {"completed", "failed"},
        )
        assert completed.status == "completed", completed.error
        assert completed.node_states["loop"]["iterations_completed"] == 3
        assert len(calls) == 3
    finally:
        release.set()
        executor.close()


def test_restart_guard_replays_completed_side_effect_without_executing_it_again(tmp_path):
    project, workspace_store, workspace, graph_store, tools, memory = _stores(
        tmp_path,
        policy={"write": "allow"},
    )
    graph = graph_store.create(
        {
            "id": "restart-guard",
            "project_id": workspace.id,
            "workspace_id": workspace.id,
            "name": "Restart Guard",
            "policies": {"write": "allow"},
            "nodes": [
                {"id": "input", "type": "input"},
                {
                    "id": "write",
                    "type": "tool",
                    "config": {
                        "tool": "write_file",
                        "arguments": {"path": "guarded.txt", "content": "first\n"},
                    },
                },
                {"id": "output", "type": "output"},
            ],
            "edges": [
                {"source": "input", "target": "write"},
                {"source": "write", "target": "output"},
            ],
        }
    )
    run = graph_store.create_run(graph)
    execution_key = f"{run.id}:write:attempt:1"
    first = tools.execute(
        workspace.id,
        "write_file",
        {"path": "guarded.txt", "content": "first\n"},
        run_id=run.id,
        idempotency_key=execution_key,
    )
    assert first["ok"] is True
    (project / "guarded.txt").write_text("external change\n", encoding="utf-8")

    states = {key: dict(value) for key, value in run.node_states.items()}
    states["input"].update(
        {"status": "completed", "attempts": 1, "output": {}, "completed_at": "checkpoint"}
    )
    states["write"].update(
        {
            "status": "running",
            "attempts": 1,
            "idempotency_key": execution_key,
            "started_at": "before-restart",
        }
    )
    graph_store.update_run(
        run.id,
        status="running",
        current_node_id="write",
        node_states=states,
    )

    executor = GraphExecutor(graph_store, tools, memory, model_runner=lambda **_: {})
    try:
        recovered = graph_store.get_run(run.id)
        assert recovered.status == "paused"
        assert recovered.node_states["input"]["status"] == "completed"
        assert recovered.node_states["write"]["recovery_guard"] == (
            "interrupted_side_effect"
        )
        with pytest.raises(GraphExecutionError, match="retry_failed_node"):
            executor.resume(run.id)
        with pytest.raises(GraphExecutionError, match="allow_side_effect_retry"):
            executor.retry_failed_node(run.id)

        executor.retry_failed_node(run.id, allow_side_effect_retry=True)
        completed = _wait_for(
            graph_store,
            run.id,
            lambda value: value.status in {"completed", "failed"},
        )
        assert completed.status == "completed", completed.error
        assert completed.node_states["write"]["metrics"]["replayed"] is True
        assert (project / "guarded.txt").read_text(encoding="utf-8") == (
            "external change\n"
        )
        kinds = [event.kind for event in workspace_store.list_events(run.id, limit=1000)]
        assert "graph_recovered" in kinds
    finally:
        executor.close()


